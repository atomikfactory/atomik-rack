#!/bin/sh
# Repository hygiene check for a public tree. Run from anywhere inside the repository:
#
#   sh scripts/check-public.sh
#
# Fails (exit 1) if a tracked file contains an absolute local path, an agent or tool attribution
# string, a secret-looking token, or if the tracked tree contains agent instruction files, build
# output, local tool directories or files larger than 5 MB. Only tracked files are examined.
set -u

cd "$(git rev-parse --show-toplevel)" || exit 2

fail=0
report() {
  printf 'FAIL: %s\n' "$1"
  fail=1
}

# Tracked files, one per line (no file in this repository has a newline in its name).
files="$(git ls-files)"

# The script itself spells out the patterns it searches for.
self="scripts/check-public.sh"

# Text files only: skip binary extensions.
text_files="$(printf '%s\n' "$files" | grep -v -E '\.(wav|png|ico|aif|aiff|flac|mp3|ogg|ttf|otf|woff2?)$' | grep -v -x "$self")"

scan() {
  # scan <label> <extended-regex> [allowlist-regex-applied-to-matching-lines]
  label="$1"
  pattern="$2"
  allow="${3:-}"
  hits="$(printf '%s\n' "$text_files" | tr '\n' '\0' | xargs -0 grep -n -I -E -e "$pattern" -- 2>/dev/null)"
  if [ -n "$allow" ] && [ -n "$hits" ]; then
    hits="$(printf '%s\n' "$hits" | grep -v -E -e "$allow")"
  fi
  if [ -n "$hits" ]; then
    report "$label"
    printf '%s\n' "$hits" | head -20
  fi
}

# 1. Absolute local paths. The allowlist is deliberately tiny: documented placeholder users
#    ("example", "me", "user", "name") in tests and documentation.
scan "absolute Windows user path" '[A-Za-z]:\\+Users\\+' '[A-Za-z]:\\+Users\\+(example|me|user|name)\\'
scan "absolute Windows drive path" '(^|[^A-Za-z0-9])[A-Z]:\\+[A-Za-z]' '(^|[^A-Za-z0-9])[A-Z]:\\+(Program Files|Windows|Plugins|Users\\+(example|me|user|name)\\)'
scan "absolute home path" '/(home|Users)/[A-Za-z0-9._-]+/' '/(home|Users)/(example|me|user|name|runner)/'

# 2. Attribution strings.
scan "attribution string" 'Co-Authored-By|Generated with|Generated by (Claude|an AI)'

# 3. Secrets.
scan "AWS access key" 'AKIA[0-9A-Z]{16}'
scan "GitHub token" 'gh[pousr]_[A-Za-z0-9]{36,}|github_pat_[A-Za-z0-9_]{22,}'
scan "private key" '-----BEGIN ([A-Z]+ )?PRIVATE KEY-----'

# 4. Tracked agent instruction files and local tool directories.
agent="$(printf '%s\n' "$files" | grep -E -i '(^|/)(CLAUDE\.md|AGENTS\.md|GEMINI\.md|\.cursorrules|\.windsurfrules|\.clinerules|copilot-instructions\.md)$|(^|/)\.(claude|cursor|codex|aider[^/]*)(/|$)')"
if [ -n "$agent" ]; then
  report "tracked agent or tool configuration files"
  printf '%s\n' "$agent"
fi

# 5. Tracked build output or local SDK directories.
tracked_dirs="$(printf '%s\n' "$files" | grep -E '^(target|tools)/')"
if [ -n "$tracked_dirs" ]; then
  report "tracked target/ or tools/ content"
  printf '%s\n' "$tracked_dirs" | head -20
fi

# 6. Files over 5 MB.
big="$(printf '%s\n' "$files" | while IFS= read -r f; do
  [ -f "$f" ] || continue
  size="$(wc -c < "$f" | tr -d ' ')"
  if [ "$size" -gt 5242880 ]; then printf '%s (%s bytes)\n' "$f" "$size"; fi
done)"
if [ -n "$big" ]; then
  report "tracked files larger than 5 MB"
  printf '%s\n' "$big"
fi

if [ "$fail" -eq 0 ]; then
  echo "check-public: OK"
fi
exit "$fail"
