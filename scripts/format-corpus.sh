#!/bin/sh
# Fills crates/model/tests/fixtures/corpus/atomik-vN.atomik, the saved-file corpus: one real
# project file for every released project-format version. Not run by CI.
#
# usage: sh scripts/format-corpus.sh [FIRST [LAST]]     (defaults 1 and the current version)
#
# A file that is already in the corpus is never rewritten. For a missing version the script takes,
# in this order:
#   1. a real file already kept in tests/fixtures (demo-vN, or seq-v7 / container-v8 for 7 and 8);
#   2. the demo project (examples/projects/demo.atomik) at the commit that introduced the version,
#      which is a file written by that version's own writer (the demo is the canonical save of
#      the demo song and is regenerated by every format bump).
# A version with neither (the writers of versions 2 to 5 predate the public history) is skipped
# with a note: the corpus test lists it as missing on purpose.
#
# To save a richer song than the demo for a version: check out the commit that introduced it in
# a throwaway worktree under target/ (git worktree add target/corpus-vN <commit>), save the song
# with that revision's writer, copy the file to the corpus and remove the worktree. Commit only
# the file.
#
# Each format bump adds the file for its new version: the release check
# (scripts/release/check-corpus.sh) fails without it.
set -eu
cd "$(dirname "$0")/.."
src=crates/model/src/project/mod.rs
fix=crates/model/tests/fixtures
out=$fix/corpus
first=${1:-1}
last=${2:-$(sed -n 's/^pub const PROJECT_VERSION: u32 = \([0-9]*\);.*/\1/p' "$src")}
mkdir -p "$out"
n=$first
while [ "$n" -le "$last" ]; do
    dest=$out/atomik-v$n.atomik
    if [ -f "$dest" ]; then
        n=$((n + 1))
        continue
    fi
    from=""
    for f in "$fix/demo-v$n.atomik" "$fix/seq-v$n.atomik" "$fix/container-v$n.atomik"; do
        if [ -f "$f" ]; then
            from=$f
            break
        fi
    done
    if [ -n "$from" ]; then
        cp "$from" "$dest"
        echo "atomik-v$n.atomik from $from"
    else
        commit=$(git log --format=%h -S"PROJECT_VERSION: u32 = $n;" -- "$src" crates/model/src/project.rs | tail -1)
        if [ -z "$commit" ] || ! git show "$commit:examples/projects/demo.atomik" > "$dest" 2>/dev/null; then
            rm -f "$dest"
            echo "version $n: no saved file to take (see the notes above)" >&2
            n=$((n + 1))
            continue
        fi
        echo "atomik-v$n.atomik from the demo at $commit"
    fi
    if ! grep -q "^  \"version\": $n,\$" "$dest"; then
        echo "version $n: $dest is not a version $n file" >&2
        rm -f "$dest"
        exit 1
    fi
    n=$((n + 1))
done
