//! Test-only stand-ins for the console devices (`atomik.channel`, `atomik.master`) with the
//! exact socket and param keys of the console contract, so the
//! model tests do not depend on the real DSP devices (param ranges are placeholders), plus a
//! few odd instruments for the auto-wiring rules.

use atomik_core::{ParamDescriptor, ParamId, Taper, Unit};
use atomik_device_sdk::{
    Device, DeviceDescriptor, DeviceFactory, DeviceKind, Direction, PrepareInfo, ProcessContext,
    Registry, SocketDescriptor, SocketId, SocketKind,
};

#[allow(clippy::too_many_arguments)]
const fn param(
    id: u32,
    key: &'static str,
    min: f32,
    max: f32,
    default: f32,
    taper: Taper,
    unit: Unit,
    discrete: bool,
) -> ParamDescriptor {
    ParamDescriptor {
        id: ParamId(id),
        key,
        name: key,
        min,
        max,
        default,
        taper,
        unit,
        discrete,
    }
}

const fn socket(
    id: u16,
    key: &'static str,
    kind: SocketKind,
    direction: Direction,
) -> SocketDescriptor {
    SocketDescriptor {
        id: SocketId(id),
        key,
        name: key,
        kind,
        direction,
    }
}

