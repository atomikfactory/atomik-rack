/// Stub `atomik.bus`: the channel's params, stages and sockets, but the summing input
/// `bus_l`/`bus_r` in place of `in_l`/`in_r`.
pub fn bus_descriptor() -> &'static DeviceDescriptor {
    static BUS: std::sync::LazyLock<&'static DeviceDescriptor> = std::sync::LazyLock::new(|| {
        let sockets: Vec<SocketDescriptor> = CHANNEL_SOCKETS
            .iter()
            .map(|s| match s.key {
                "in_l" => SocketDescriptor {
                    key: "bus_l",
                    name: "Bus L",
                    direction: Direction::SummingInput,
                    ..*s
                },
                "in_r" => SocketDescriptor {
                    key: "bus_r",
                    name: "Bus R",
                    direction: Direction::SummingInput,
                    ..*s
                },
                _ => *s,
            })
            .collect();
        Box::leak(Box::new(DeviceDescriptor {
            stages: &CHANNEL_STAGES,
            type_id: "atomik.bus",
            name: "Console Bus",
            kind: DeviceKind::Mixer,
            version: 1,
            params: &CHANNEL_PARAMS,
            sockets: Box::leak(sockets.into_boxed_slice()),
        }))
    });
    *BUS
}

struct Stub(&'static DeviceDescriptor);

impl Device for Stub {
    fn descriptor(&self) -> &'static DeviceDescriptor {
        self.0
    }
    fn prepare(&mut self, _: &PrepareInfo) {}
    fn reset(&mut self) {}
    fn set_param(&mut self, _: ParamId, _: f32) {}
    fn process(&mut self, _: &mut ProcessContext<'_>) {}
}

/// The built-in devices plus the stub channel and master.
pub fn console_registry() -> Registry {
    let mut r = Registry::new();
    r.register(atomik_devices::poly_synth::factory()).unwrap();
    r.register(atomik_devices::stereo_delay::factory()).unwrap();
    r.register(atomik_devices::line_mixer::factory()).unwrap();
    r.register(DeviceFactory {
        descriptor: &CHANNEL,
        create: || Box::new(Stub(&CHANNEL)),
    })
    .unwrap();
    r.register(DeviceFactory {
        descriptor: &MASTER,
        create: || Box::new(Stub(&MASTER)),
    })
    .unwrap();
    r.register(DeviceFactory {
        descriptor: bus_descriptor(),
        create: || Box::new(Stub(bus_descriptor())),
    })
    .unwrap();
    r
}

/// [`console_registry`] with the real `atomik.channel` in place of the stub (the real param
/// table, with the parallel compressor and the other params the contract stub lacks).
pub fn console_registry_real_channel() -> Registry {
    let mut r = Registry::new();
    r.register(atomik_devices::poly_synth::factory()).unwrap();
    r.register(atomik_devices::stereo_delay::factory()).unwrap();
    r.register(atomik_devices::line_mixer::factory()).unwrap();
    r.register(atomik_devices::channel::factory()).unwrap();
    r.register(DeviceFactory {
        descriptor: &MASTER,
        create: || Box::new(Stub(&MASTER)),
    })
    .unwrap();
    r
}

pub fn chan(k: &str, source: Option<&str>) -> ConsoleChannel {
    ConsoleChannel {
        channel: key(k),
        source: source.map(key),
    }
}

/// Four synths (bass, lead and keys have channels; pad has none), two delays (one on return
/// 1), three channel strips and the master. The keys strip is soloed (and muted, which solo
/// overrides), the lead strip is muted.
pub fn console_doc() -> RackDoc {
    let mut doc = reference_doc();
    let mut bass = device("bass", "atomik.poly-synth", "Bass");
    bass.color = Some([0xe0, 0x8a, 0x3c]);
    let mut lead = device("lead", "atomik.poly-synth", "Lead");
    lead.color = Some([0x5f, 0xb4, 0xe6]);
    let keys = device("keys", "atomik.poly-synth", "Keys");
    let pad = device("pad", "atomik.poly-synth", "Pad");
    let delay = device("delay", "atomik.stereo-delay", "Stereo Delay");
    let echo = device("echo", "atomik.stereo-delay", "Echo");
    let mut ch1 = device("ch-bass", "atomik.channel", "Channel 1");
    for (k, v) in [
        ("fader", 0.62),
        ("eq.on", 1.0),
        ("eq.lf.gain", 4.5),
        ("eq.hmf.gain", -3.0),
        ("comp.on", 1.0),
        ("comp.threshold", -18.0),
        ("send1.on", 1.0),
        ("send1.level", -12.0),
        ("pan", -30.0),
    ] {
        ch1.params.insert(k.into(), v);
    }
    let mut ch2 = device("ch-lead", "atomik.channel", "Channel 2");
    for (k, v) in [
        ("mute", 1.0),
        ("hpf.on", 1.0),
        ("hpf.freq", 160.0),
        ("width", 64.0),
        ("fader", 0.75),
    ] {
        ch2.params.insert(k.into(), v);
    }
    let mut ch3 = device("ch-keys", "atomik.channel", "Channel 3");
    for (k, v) in [
        ("solo", 1.0),
        ("mute", 1.0),
        ("fader", 0.9),
        ("send2.on", 1.0),
        ("send2.pre", 1.0),
        ("send2.level", -3.0),
        ("pan", 45.0),
    ] {
        ch3.params.insert(k.into(), v);
    }
    let mut master = device("master", "atomik.master", "Master");
    for (k, v) in [
        ("comp.on", 1.0),
        ("return1.level", -6.0),
        ("return1.pan", -20.0),
        ("monitor.dim", 1.0),
    ] {
        master.params.insert(k.into(), v);
    }
    doc.devices = vec![bass, lead, keys, pad, delay, echo, ch1, ch2, ch3, master];
    doc.cables.clear();
    let mut returns: [Option<atomik_model::DeviceKey>; 8] = Default::default();
    returns[0] = Some(key("delay"));
    doc.console = Console {
        channels: vec![
            chan("ch-bass", Some("bass")),
            chan("ch-lead", Some("lead")),
            chan("ch-keys", Some("keys")),
        ],
        buses: Vec::new(),
        master: Some(key("master")),
        returns,
        compensation: true,
        ..Console::default()
    };
    doc
}

/// [`console_doc`] with two output buses and the routing cables the output selector reads:
/// `ch-bass` plays to Audio I/O pair 2 (3+4), `ch-lead` to `bus` ("Drums"), `ch-keys` (soloed) to
/// `bus-2` ("Synths"), `bus-2` into `bus`, `bus` to the master, which feeds pair 1 (1+2). The
/// project has 4 output channels.
pub fn bus_doc() -> RackDoc {
    let mut doc = console_doc();
    doc.output_channels = 4;
    doc.devices.push(device("bus", "atomik.bus", "Drums"));
    doc.devices.push(device("bus-2", "atomik.bus", "Synths"));
    doc.console.buses = vec![
        ConsoleBus {
            bus: key("bus"),
            name: "Drums".into(),
        },
        ConsoleBus {
            bus: key("bus-2"),
            name: "Synths".into(),
        },
    ];
    let wire = |from: &str, l: &str, to: &str| {
        [
            cable((from, "out_l"), (to, l)),
            cable((from, "out_r"), (to, &l.replace("_l", "_r"))),
        ]
    };
    doc.cables = [
        wire("ch-lead", "bus_l", "bus"),
        wire("ch-keys", "bus_l", "bus-2"),
        wire("bus-2", "bus_l", "bus"),
        wire("bus", "bus_l", "master"),
        [
            cable(("ch-bass", "out_l"), ("interface", "out_3")),
            cable(("ch-bass", "out_r"), ("interface", "out_4")),
        ],
        [
            cable(("master", "main_l"), ("interface", "out_1")),
            cable(("master", "main_r"), ("interface", "out_2")),
        ],
    ]
    .into_iter()
    .flatten()
    .collect();
    doc
}

/// 760 for the strips plus the snapshot bar.
pub const CONSOLE_BOUNDS: Rect = Rect::new(0.0, 0.0, 1100.0, 784.0);

/// A synced console view over `CONSOLE_BOUNDS` at 1x.
pub fn console_view(doc: &RackDoc, reg: &Registry) -> ConsoleView {
    let mut v = ConsoleView::new(Theme::dark());
    v.set_bounds(CONSOLE_BOUNDS);
    v.sync(doc, reg);
    v
}
